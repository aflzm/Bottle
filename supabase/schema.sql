-- “求真·问道” 学术诚信漂流瓶 · Supabase 数据库初始化
-- 使用方法：Supabase Dashboard → SQL Editor → 粘贴执行

-- ───────────── 漂流瓶表 ─────────────
create table if not exists public.bottles (
    id bigint generated by default as identity primary key,
    nickname text not null default '匿名同学',
    content text not null,
    type text not null default 'blue',
    visible boolean not null default true,
    created_at timestamptz not null default now()
);

-- 兼容早期版本：补齐 visible 字段
alter table public.bottles
    add column if not exists visible boolean not null default true;

-- 类型约束（red / blue / green / warm）
alter table public.bottles
    drop constraint if exists bottles_type_check;
alter table public.bottles
    add constraint bottles_type_check
    check (type in ('red', 'blue', 'green', 'warm'));

-- ───────────── 讨论表 ─────────────
create table if not exists public.comments (
    id bigint generated by default as identity primary key,
    bottle_id bigint not null references public.bottles (id) on delete cascade,
    nickname text not null default '匿名同学',
    content text not null,
    created_at timestamptz not null default now()
);

create index if not exists idx_comments_bottle_id on public.comments (bottle_id);

-- ───────────── 点赞表 ─────────────
-- 漂流瓶与讨论共用一张表，target_type 区分对象；visitor_id 用于同一设备去重
create table if not exists public.bottle_likes (
    id bigint generated by default as identity primary key,
    target_type text not null check (target_type in ('bottle', 'comment')),
    target_id text not null,
    visitor_id text not null,
    created_at timestamptz not null default now(),
    constraint bottle_likes_unique unique (target_type, target_id, visitor_id)
);

create index if not exists idx_bottle_likes_target
    on public.bottle_likes (target_type, target_id);

-- ───────────── 行级安全 ─────────────
alter table public.bottles      enable row level security;
alter table public.comments     enable row level security;
alter table public.bottle_likes enable row level security;

-- 匿名用户可读公开漂流瓶 + 海面漂流瓶（前端按 visible 分流）
drop policy if exists "bottles readable by everyone" on public.bottles;
create policy "bottles readable by everyone"
    on public.bottles for select
    to anon, authenticated
    using (true);

drop policy if exists "bottles insert by everyone" on public.bottles;
create policy "bottles insert by everyone"
    on public.bottles for insert
    to anon, authenticated
    with check (true);

-- 讨论：可读可写，不允许改删
drop policy if exists "comments readable by everyone" on public.comments;
create policy "comments readable by everyone"
    on public.comments for select
    to anon, authenticated
    using (true);

drop policy if exists "comments insert by everyone" on public.comments;
create policy "comments insert by everyone"
    on public.comments for insert
    to anon, authenticated
    with check (true);

-- 点赞：可读可写，不允许改删（去重靠唯一约束）
drop policy if exists "likes readable by everyone" on public.bottle_likes;
create policy "likes readable by everyone"
    on public.bottle_likes for select
    to anon, authenticated
    using (true);

drop policy if exists "likes insert by everyone" on public.bottle_likes;
create policy "likes insert by everyone"
    on public.bottle_likes for insert
    to anon, authenticated
    with check (true);

-- 取消点赞需要删除权限（匿名环境无法校验身份，删除范围由前端按 visitor_id 限定）
drop policy if exists "likes delete by everyone" on public.bottle_likes;
create policy "likes delete by everyone"
    on public.bottle_likes for delete
    to anon, authenticated
    using (true);
